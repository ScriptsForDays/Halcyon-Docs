// Writes play/icons.js: the Lucide icons Halcyon uses, as SVG markup, so the
// demo draws the same glyphs the library shows in Roblox.
//
//   node scripts/build-icons.mjs [path to the library repo]
//
// Icons come from lucide-static (ISC) at a pinned version. The Discord mark
// is from Simple Icons (CC0).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const LUCIDE = "1.72.0";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIBRARY = process.argv[2] || join(ROOT, "..", "YaxUI");
const DISCORD =
	'<path fill="currentColor" stroke="none" d="M20.317 4.369a19.79 19.79 0 0 0-4.885-1.515.074.074 0 0 0-.079.037c-.21.375-.444.864-.608 1.25a18.27 18.27 0 0 0-5.487 0 12.64 12.64 0 0 0-.617-1.25.077.077 0 0 0-.079-.037A19.74 19.74 0 0 0 3.677 4.37a.07.07 0 0 0-.032.027C.533 9.046-.32 13.58.099 18.057a.082.082 0 0 0 .031.057 19.9 19.9 0 0 0 5.993 3.03.078.078 0 0 0 .084-.028c.462-.63.874-1.295 1.226-1.994a.076.076 0 0 0-.041-.106 13.1 13.1 0 0 1-1.872-.892.077.077 0 0 1-.008-.128c.126-.094.252-.192.372-.291a.074.074 0 0 1 .077-.01c3.928 1.793 8.18 1.793 12.062 0a.074.074 0 0 1 .078.009c.12.099.246.198.373.292a.077.077 0 0 1-.006.127 12.3 12.3 0 0 1-1.873.892.077.077 0 0 0-.041.107c.36.698.772 1.362 1.225 1.993a.076.076 0 0 0 .084.028 19.84 19.84 0 0 0 6.002-3.03.077.077 0 0 0 .032-.054c.5-5.177-.838-9.674-3.549-13.66a.061.061 0 0 0-.031-.03zM8.02 15.331c-1.183 0-2.157-1.085-2.157-2.419 0-1.333.956-2.419 2.157-2.419 1.21 0 2.176 1.096 2.157 2.42 0 1.333-.956 2.418-2.157 2.418zm7.975 0c-1.183 0-2.157-1.085-2.157-2.419 0-1.333.955-2.419 2.157-2.419 1.21 0 2.176 1.096 2.157 2.42 0 1.333-.946 2.418-2.157 2.418z"/>';

const data = readFileSync(join(LIBRARY, "src", "Core", "IconData.luau"), "utf8");
const names = [...data.matchAll(/\["([a-z0-9-]+)"\]/g)].map((m) => m[1]);
// Each icon's Roblox asset id, so an image the library set by id draws as
// the same icon here.
const assets = {};
for (const [, name, id] of data.matchAll(/\["([a-z0-9-]+)"\]\s*=\s*"(rbxassetid:\/\/\d+)"/g)) assets[id] = name;
// Icons the demo needs beyond the library's own set.
for (const extra of ["user-round", "image"]) if (!names.includes(extra)) names.push(extra);

const icons = {};
const missing = [];
for (const name of names) {
	const response = await fetch(`https://cdn.jsdelivr.net/npm/lucide-static@${LUCIDE}/icons/${name}.svg`);
	if (!response.ok) {
		missing.push(name);
		continue;
	}
	const svg = await response.text();
	const inner = svg
		.replace(/<!--[\s\S]*?-->/g, "")
		.replace(/^[\s\S]*?<svg[^>]*>/, "")
		.replace(/<\/svg>[\s\S]*$/, "")
		.replace(/\s+/g, " ")
		.trim();
	icons[name] = inner;
}
icons.discord = DISCORD;

const body = `// Generated by scripts/build-icons.mjs from lucide-static ${LUCIDE} (ISC) and
// Simple Icons (CC0, the Discord mark). Do not edit by hand.
export const ICONS = ${JSON.stringify(icons, null, "\t")};

export const ASSETS = ${JSON.stringify(assets, null, "\t")};

export function icon(name) {
	const inner = ICONS[name] || ICONS.image;
	return \`<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${inner}</svg>\`;
}
`;
writeFileSync(join(ROOT, "play", "icons.js"), body);
console.log(`wrote ${Object.keys(icons).length} icons${missing.length ? `; not found: ${missing.join(", ")}` : ""}`);
